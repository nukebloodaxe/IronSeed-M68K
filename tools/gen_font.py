#!/usr/bin/env python3
"""gen_font.py data.pas OUT.i [intro.pas] - extract the 3 x 82 glyph 4x6 font (const 'font') as dc.b,
and, if intro.pas is given, the intro's own 84-glyph font (font 2 plus the two halves of a (c) sign)
as txt_font_intro."""
import re, sys
src = open(sys.argv[1], encoding='latin-1').read()
m = re.search(r'font:\s*array\[0\.\.2,1\.\.82\] of fonttype\s*=\s*\((.*?)\);', src, re.S)
nums = [int(x) for x in re.findall(r'\d+', m.group(1))]
assert len(nums) == 3 * 82 * 3, len(nums)
L = ['; font.i - GENERATED by tools/gen_font.py from data.pas (const font). 3 fonts x 82 glyphs x 3 bytes;',
     '; each byte = 2 rows of 4 pixels (high nibble first), bit 7/3 = leftmost.', 'txt_font:']
for f in range(3):
    for g in range(82):
        i = (f * 82 + g) * 3
        L.append('\tdc.b\t%d,%d,%d' % tuple(nums[i:i + 3]))
if len(sys.argv) > 3:
    isrc = open(sys.argv[3], encoding='latin-1').read()
    m = re.search(r'font:\s*array\[1\.\.84\] of fonttype\s*=\s*\((.*?)\);', isrc, re.S)
    inums = [int(x) for x in re.findall(r'\d+', m.group(1))]
    assert len(inums) == 84 * 3, len(inums)
    L.append('txt_font_intro:\t\t\t; intro.pas font, 84 glyphs (83/84 = the (c) sign)')
    for g in range(84):
        L.append('\tdc.b\t%d,%d,%d' % tuple(inums[g * 3:g * 3 + 3]))
    m = re.search(r'bigfont:\s*array\[1\.\.82\] of bigfonttype\s*=\s*\((.*?)\);', isrc, re.S)
    bnums = [int(x) for x in re.findall(r'\d+', m.group(1))]
    assert len(bnums) == 82 * 8, len(bnums)
    L.append('txt_bigfont:\t\t\t; intro.pas bigfont, 82 glyphs of 8 rows (bit 7 = left)')
    for g in range(82):
        L.append('\tdc.b\t' + ','.join(str(v) for v in bnums[g * 8:g * 8 + 8]))
open(sys.argv[2], 'w').write('\n'.join(L) + '\n')
print('font: %d glyphs' % (3 * 82))
