#!/usr/bin/env python3
"""sincos_model.py - the integer model of kernel/fp.s's fast sin/cos (Phase 6i), and the table
generator. The x87's fsin/fcos reduce by a 66-bit pi/2 and are then (nearly) correctly rounded to
64 bits; this model reduces exactly by the same pi/2, evaluates sin and cos together to ~2^-93
with a table of sin/cos(j/512) (96-bit) and short polynomials in b = r - j/512, and rounds once.
Every operation here is one the 68000 code does (exact products, floors), so the ST's results must
equal this model's bit for bit (tests/check_sincos.py).
  python3 tools/sincos_model.py --table OUT.i   writes the table (fps_tab) and the constant Pm."""
import sys
from fractions import Fraction as F

def _pi(bits):                      # pi to `bits` bits (Machin), as a Fraction
    one = 1 << (bits + 20)
    def atan_inv(n):
        s = t = one // n; n2 = n * n; k = 1; sign = -1
        while t:
            t //= n2; s += sign * (t // (2 * k + 1)); sign = -sign; k += 1
        return s
    return F(4 * (4 * atan_inv(5) - atan_inv(239)), one)
PI = _pi(200)
def _rne(v):                        # round half even of a Fraction
    q, r = divmod(v.numerator, v.denominator)
    if 2 * r > v.denominator or (2 * r == v.denominator and q & 1): q += 1
    return q
PM = _rne(PI / 2 * 2 ** 65)        # pi/2 in 66 bits (the x87's), units 2^-65
NTAB = 404
def _sincos_frac(a):                # sin/cos of a Fraction by Taylor (|a| < 1), 200 bits
    s = c = F(0); t = F(1); n = 0
    while True:
        term = t
        if n % 2 == 0: c += term if (n // 2) % 2 == 0 else -term
        else: s += term if (n // 2) % 2 == 0 else -term
        n += 1; t = t * a / n
        if t == 0 or abs(t) < F(1, 2 ** 220): break
    return s, c
def _table():
    out = []
    for j in range(NTAB):
        s, c = _sincos_frac(F(j, 512))
        out.append((_rne(s * 2 ** 95), _rne(c * 2 ** 95)))
    return out
TAB = _table()

def sincos(se, m):
    """x = extended (se, m). Returns (sin, cos) as extended (se, m) pairs, or None (fallback)."""
    if m == 0: return None
    neg = se >> 15; E = (se & 0x7fff) - 16383
    if E > 13 or E < -12: return None
    if E >= -2: X = m << (E + 2)
    else:
        sh = -2 - E
        if m & ((1 << sh) - 1): return None
        X = m >> sh
    q16 = X >> 49
    k = (q16 * 41722 + (1 << 31)) >> 32
    R = X - k * PM
    while 2 * R > PM: R -= PM; k += 1
    while 2 * R < -PM: R += PM; k -= 1
    sr = -1 if R < 0 else 1; A = abs(R)
    if A == 0: return None
    if A < (1 << 41):               # |r| < 2^-24: sin A = A - A^3/6, cos A = 1 - A^2/2
        sA = (A << 30) - ((A * A * A) >> 100) // 6
        cA = (1 << 95) - ((A * A) >> 36)
        return _out(neg, k, sr, sA, cA)
    j = (A + (1 << 55)) >> 56
    b = A - (j << 56); sb = -1 if b < 0 else 1; Bm = abs(b)
    if Bm >= (1 << 55): return None
    S, C = TAB[j]
    Q = (Bm * Bm) >> 46
    Q2 = (Q * Q) >> 84
    W = Q >> 32
    W3 = (((W * W) >> 32) * W) >> 40
    es = Q // 6 - Q2 // 120 + W3 // 5040
    ec = (Q >> 1) - Q2 // 24 + W3 // 720
    CB = (C * Bm) >> 65; SB = (S * Bm) >> 65
    CBe = ((CB >> 21) * es) >> 63; SBe = ((SB >> 21) * es) >> 63
    Sec = (S * ec) >> 84; Cec = (C * ec) >> 84
    sA = S - Sec + sb * (CB - CBe)
    cA = C - Cec - sb * (SB - SBe)
    assert sA > 0 and cA > 0
    return _out(neg, k, sr, sA, cA)

def _out(neg, k, sr, sA, cA):
    sv, cv = sr * sA, cA            # sin r, cos r (units 2^-95)
    if neg: sv = -sv                # x < 0: r and k negate: sin(-x) = -sin x, cos(-x) = cos x
    q = k & 3                       # quadrant of |x|
    vs = [sv, cv, -sv, -cv][q] if not neg else [sv, -cv, -sv, cv][q]
    vc = [cv, -sv, -cv, sv][q] if not neg else [cv, sv, -cv, -sv][q]
    return _ext(vs), _ext(vc)

def _ext(v):                        # v units 2^-95 -> extended, round half even to 64 bits
    s = 0x8000 if v < 0 else 0; v = abs(v)
    n = v.bit_length()
    if n > 64:
        sh = n - 64; mm = v >> sh; rem = v & ((1 << sh) - 1); half = 1 << (sh - 1)
        if rem > half or (rem == half and mm & 1): mm += 1
        if mm >> 64: mm >>= 1; n += 1
    else:
        mm = v << (64 - n)
    return (s | (16383 + n - 1 - 95), mm)

if __name__ == '__main__' and len(sys.argv) > 2 and sys.argv[1] == '--table':
    with open(sys.argv[2], 'w') as f:
        f.write('; generated by tools/sincos_model.py - kernel/fp.s fast sin/cos: pi/2 (66 bits, units 2^-65),\n')
        f.write('; sin and cos of j/512 in units 2^-95, 12 bytes each (3 longs, big-endian), j = 0..%d\n' % (NTAB - 1))
        f.write('fps_pm:\tdc.l\t$%08x,$%08x,$%08x\n' % ((PM >> 64) & 0xffffffff, (PM >> 32) & 0xffffffff, PM & 0xffffffff))
        H = PM >> 1                 # R > h / R < -h: |R| beyond pi/4 (PM/2), for PM odd or even
        f.write('fps_h:\tdc.l\t$%08x,$%08x,$%08x\n' % ((H >> 64) & 0xffffffff, (H >> 32) & 0xffffffff, H & 0xffffffff))
        f.write('fps_tab:\n')
        for s, c in TAB:
            assert s < 1 << 96 and c < 1 << 96
            f.write('\tdc.l\t$%08x,$%08x,$%08x,$%08x,$%08x,$%08x\n' % (s >> 64, (s >> 32) & 0xffffffff, s & 0xffffffff,
                                                               c >> 64, (c >> 32) & 0xffffffff, c & 0xffffffff))
