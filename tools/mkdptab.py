#!/usr/bin/env python3
"""mkdptab.py OUT.i - tables for c_utils.c's drawing in MAIN.PRG (doubles, as C computes them):
circle: (int16)(y + yy*0.9) - y and (int16)(y - yy*0.9) - y for yy = 0..100 (checked to be the
same for every y 0..199); pieslice: (int)(j*0.9) for j = -100..100."""
import sys
E = 0.9
up, dn = [], []
for yy in range(101):
    u = {int(y + yy * E) - y for y in range(200)}
    d = {int(y - yy * E) - y for y in range(200) if y - yy * E >= 0}
    assert len(u) == 1 and len(d) <= 1, yy
    up.append(u.pop()); dn.append(d.pop() if d else -yy)
out = ['; generated by tools/mkdptab.py\n', 'ct_up:\n']
for k in range(0, 101, 16): out.append('\tdc.b\t' + ','.join(str(v) for v in up[k:k + 16]) + '\n')
out.append('ct_dn:\n')
for k in range(0, 101, 16): out.append('\tdc.b\t' + ','.join(str(v) for v in dn[k:k + 16]) + '\n')
out.append('\teven\nct_pie:\t\t\t\t; (int)(j*0.9) for j = -100..100, index j+100\n')
pie = [int(j * E) for j in range(-100, 101)]
for k in range(0, 201, 16): out.append('\tdc.b\t' + ','.join(str(v) for v in pie[k:k + 16]) + '\n')
out.append('\teven\n')
open(sys.argv[1], 'w').write(''.join(out))
