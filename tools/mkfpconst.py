#!/usr/bin/env python3
"""mkfpconst.py OUT.i - constants for kernel/fp.s as 80-bit extended (se.w, hi.l, lo.l), rounded to
nearest from exact rationals: 2/pi, pi/2 (and split into a 40-bit head + 64-bit tail for argument
reduction), Taylor coefficients of sin, cos (to x^21 / x^20) and arctan (to x^29)."""
import sys
from fractions import Fraction as F

def pi_frac(digits=80):
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239), fixed point with 10^(digits+10)
    one = 10 ** (digits + 10)
    def atan_inv(x):
        s, t, n, sign = 0, one // x, 1, 1
        x2 = x * x
        while t:
            s += sign * (t // n)
            t //= x2; n += 2; sign = -sign
        return s
    return F(16 * atan_inv(5) - 4 * atan_inv(239), one)

def ext(v, bits=64):
    """(se, mantissa) of v rounded to `bits` significant bits (nearest even), x87 layout."""
    if v == 0: return 0, 0
    sign = 0x8000 if v < 0 else 0
    v = abs(v); e = 0
    while v >= 2: v /= 2; e += 1
    while v < 1: v *= 2; e -= 1
    m = v * (1 << (bits - 1))              # in [2^(bits-1), 2^bits)
    q, r = divmod(m.numerator, m.denominator)
    if 2 * r > m.denominator or (2 * r == m.denominator and q & 1): q += 1
    if q >> bits: q >>= 1; e += 1
    q <<= (64 - bits)
    return sign | (e + 16383), q

def dc(name, v, bits=64):
    se, m = ext(v, bits)
    return '%s\tdc.w\t$%04x\n\tdc.l\t$%08x,$%08x\n' % (name, se, m >> 32, m & 0xffffffff)

def fact(n):
    r = 1
    for i in range(2, n + 1): r *= i
    return r

pi = pi_frac()
pio2 = pi / 2
out = ['; generated by tools/mkfpconst.py - constants for kernel/fp.s\n']
out.append(dc('fpc_2opi:', 2 / pi))
out.append(dc('fpc_pio2:', pio2))
se, m = ext(pio2, 40); a = F(m, 1 << 63) * F(2) ** ((se & 0x7fff) - 16383)
out.append(dc('fpc_pio2a:', a, 40))
out.append(dc('fpc_pio2b:', pio2 - a))
out.append('fpc_sin:\n')
for k in range(10, -1, -1): out.append(dc('', F((-1) ** k, fact(2 * k + 1))))
out.append('fpc_cos:\n')
for k in range(10, -1, -1): out.append(dc('', F((-1) ** k, fact(2 * k))))
out.append('fpc_atan:\n')
for k in range(14, -1, -1): out.append(dc('', F((-1) ** k, 2 * k + 1)))
open(sys.argv[1], 'w').write(''.join(out))
