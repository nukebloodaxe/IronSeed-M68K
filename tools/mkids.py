#!/usr/bin/env python3
"""mkids.py DATA.PAS OUT.i - data.pas's named integer constants (ID_*, OPT_*, DMG_*, JOBTYPE_*,
SHPTYP*, SHPTYPE_*, WNDACT_*, WNDORDER_*, SHLD_*, ALRT_*, and the plain numeric constants like
maxcargo) as asm equates."""
import re, sys
src = open(sys.argv[1], encoding='latin1').read()
src = re.sub(r'\{[^}]*\}', '', src)
out = ['; generated by tools/mkids.py from data.pas\n']
seen = set()
for name, val in re.findall(r'\b([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(-?\d+)\s*;', src):
    if name.lower() in seen: continue
    seen.add(name.lower())
    out.append('%s\tequ\t%s\n' % (name if name.isupper() or name.startswith(('ID_', 'OPT_')) else name.upper(), val))
open(sys.argv[2], 'w').write(''.join(out))
