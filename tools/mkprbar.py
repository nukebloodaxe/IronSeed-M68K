#!/usr/bin/env python3
"""mkprbar.py OUT.i : saveload.pas printinfo's progress bar columns, round(j*0.15+85) for
j = 1..1000, as FPC computes them (0.15 is not double-exact: x87 extended, banker's rounding) -
compiled and run with FPC itself. Writes pr_bar: dc.b (column - 85) x 1000."""
import os, subprocess, sys, tempfile
d = tempfile.mkdtemp()
open(d + '/b.pas', 'w').write('{$mode tp}\nprogram pbar;\nvar j: integer; f: file;\n b: array[1..1000] of byte;\n'
                              'begin\n for j:=1 to 1000 do b[j]:=round(j*0.15+85)-85;\n'
                              ' assign(f, paramstr(1)); rewrite(f, 1); blockwrite(f, b, 1000); close(f);\nend.\n')
subprocess.run(['fpc', '-O1', d + '/b.pas', '-o' + d + '/b'], check=True, stdout=subprocess.DEVNULL)
subprocess.run([d + '/b', d + '/out.bin'], check=True)
b = open(d + '/out.bin', 'rb').read()
L = ['; generated by tools/mkprbar.py: round(j*0.15+85)-85 for j = 1..1000 (FPC x87)', 'pr_bar:']
for k in range(0, 1000, 25):
    L.append('\tdc.b\t' + ','.join(str(x) for x in b[k:k + 25]))
open(sys.argv[1], 'w').write('\n'.join(L) + '\n')
