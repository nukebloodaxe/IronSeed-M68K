#!/usr/bin/env python3
"""mkending.py SRC_DATA OUT_DATA ENDING_PAS OUT_INC [preview_dir] - data for ending.pas (endgame) in MAIN.PRG.

The ending shows end1-end4 (fadein, wait, halffading: colours 16-255 to half brightness, then
bigprintxy text in the grey ramp 4-15), the end5-over-end6 scroll (scrollend5), end5's text, the
credits (writestr2 on black, main.pal 0-31, dothefade) and intro2. Each picture gets two band
designs, because the text needs grey slots the bright picture does not:
  ENDnA.ISP/.CHK  n=1-4: the picture (CHK + its palette: loadscreen sets colors)
  ENDnB.ISP       n=1-5: fitted on the half-bright picture with the scene's exact text over it;
                  its planar background is the half-bright picture (switched in after halffading)
  ENDS.ISP        the scroll: fitted on end5 sliding down over end6 (end5's palette); planar = end6
  ENDSCR.DAT      8 x 32000: end5 and end6 as planar through each of ENDS's 4 band LUTs
                  ([band][end5, end6]): the ST composes a scroll step from whole rows
  END5.CHK/END6.CHK the chunky pictures (END5 with its palette; END6 has none)
  CRED.ISP/.CHK   the credits (black; colours 0-31 of main.pal, 31 its own slot for dothefade)
  INTRO2E.ISP/.CHK intro2 (+ palette)
  OUT_INC         endtext.i: eg_text1-5 (dc.w y, the string; -1 ends), eg_credtext, eg_bigfont, eg_splits
The texts and the big font are read from ending.pas itself."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import numpy as np
import cpr2st as c, cgmodel as cm, bandfit as bf
from mkmain import save_mode, snap_to_reps, preview


def pas_strings(src):
    """bigprintxy calls per scene, in order: [(y, text)] lists"""
    body = src[src.index('procedure endgame;\nbegin'):]
    scenes, cur = [], None
    for line in body.split('\n'):
        if re.search(r"loadscreen\(loc_data\(\)\+'end\d'", line) or 'scrollend5;' in line:
            cur = []; scenes.append(cur)
        m = re.match(r"\s*bigprintxy\((\d+),(\d+),'(.*)'\);", line)
        if m and cur is not None:
            cur.append((int(m.group(2)), m.group(3).replace("''", "'")))
    return scenes


def bigfont_of(src):
    t = src[src.index('bigfont: array'):src.index(');', src.index('bigfont: array'))]
    nums = [int(x) for x in re.findall(r'\d+', t.split('=', 1)[1])]
    return [nums[i * 8:i * 8 + 8] for i in range(82)]


def bigprintxy(img, x1, y1, s, tcolor, bigfont):
    for ch in s:
        letter = cm.letter(ch)
        t = tcolor
        y = y1
        for i in range(7):
            x = x1
            y += 1
            for a in range(7, -1, -1):
                x += 1
                if bigfont[letter - 1][i] & (1 << a):
                    img[y, x] = t & 255
                    if x + 1 < 320: img[y, x + 1] = (t >> 1) & 255
            t -= 1
        x1 += 8


def half(pal):
    """halffading's last step: round(32*colors/64) (banker's) for colours 16-255"""
    h = pal.copy().astype(int)
    v = h[16:] * 32
    q, r = v // 64, v % 64
    h[16:] = q + (r > 32) + ((r == 32) & (q % 2 == 1))
    return h


def flat_print(img, x1, y1, s, tcolor, font):
    """ending.pas printxy2: flat, transparent"""
    x1 += 4
    for ch in s:
        g = font[cm.letter(ch) - 1]
        for row in range(6):
            bits = (g[row // 2] >> (4 if row % 2 == 0 else 0)) & 15
            for k in range(4):
                if bits & (8 >> k): img[y1 + 1 + row, x1 + 1 + k] = tcolor
        x1 += 5


def writestr2(s1, s2, s3, font):
    img = np.zeros((200, 320), np.uint8)
    js = [156 - (len(s) * 5) // 2 for s in (s1, s2, s3)]
    for i in range(31, -1, -1):
        for (s, j, yc) in ((s1, js[0], 90), (s2, js[1], 100), (s3, js[2], 110)):
            for (dx, dy) in ((-i, -i), (-i, i), (i, -i), (i, i)):
                flat_print(img, j + dx, yc + dy, s, 31 - i, font)
    return img


CREDITS = [('A', 'Destiny: Virtual', 'Designed Game'), ('Code Master:', 'Robert W.', 'Morgan III'),
           ('World Design:', 'Jeremy', 'Holt'), ('Soundtrak:', 'Andrew G. Sega', ' Necros of the Psychic Monks'),
           ('Sound Code:', 'Otto', 'Chrons'), ('Design Consultant:', 'Chris P.', 'Cash'),
           ('Scientific Advisor:', 'Jeff', 'Smith'), ('Special Thanks:', 'PJ Beachem, Ben Vandergrift,', 'and Alex Boster')]


def pstr(s):
    b = bytes([len(s)]) + s.encode('latin1')
    if len(b) % 2: b += b'\0'
    return '\tdc.b\t' + ','.join(str(x) for x in b) + '\t; ' + s.replace(';', ',')


def write_inc(fn, scenes, bigfont, splits):
    L = ['; endtext.i - generated by tools/mkending.py from ending.pas (texts, credits, big font)']
    for n, sc in enumerate(scenes):
        L.append('eg_text%d:' % (n + 1))
        for (y, t) in sc:
            L.append('\tdc.w\t%d' % y); L.append(pstr(t))
        L.append('\tdc.w\t-1')
    L.append('eg_credtext:')
    for tr in CREDITS:
        for t in tr: L.append(pstr(t))
    L.append('eg_bigfont:')
    for g in bigfont: L.append('\tdc.b\t' + ','.join(map(str, g)))
    L.append('eg_splits:\tdc.w\t' + ','.join(map(str, splits)))
    open(fn, 'w').write('\n'.join(L) + '\n')


def main():
    src, out, pas, inc = sys.argv[1:5]
    prev = sys.argv[5] if len(sys.argv) > 5 else None
    P = open(pas, errors='replace').read()
    scenes = pas_strings(P)
    assert len(scenes) == 5, len(scenes)
    bigfont = bigfont_of(P)
    font = cm.load_font()[0]
    pics = {}
    for n in range(1, 7):
        w, h, img, pal, _ = c.read_cpr(os.path.join(src, 'end%d.cpr' % n))
        pics[n] = (img, pal)
    for n in range(1, 5):
        img, pal = pics[n]
        a = bf.fit(bf.hist_of([img]), pal)
        snap_to_reps(a, pal)
        save_mode(out, 'END%dA' % n, a, img, pal)
        print('END%dA: splits' % n, a.splits, 'err %.0f' % a.err)
    for n in range(1, 6):
        img, pal = pics[n]
        hp = half(pal)
        im = img.copy()
        for (y, s) in scenes[n - 1]:
            bigprintxy(im, 0, y, s, 15, bigfont)
        b = bf.fit(bf.hist_of([im]), hp)
        snap_to_reps(b, hp)
        open(os.path.join(out, 'END%dB.ISP' % n), 'wb').write(bytes(b.isp_header()) + c.planar(b.slots(img))[1])
        print('END%dB: splits' % n, b.splits, 'err %.0f' % b.err)
        if prev:
            preview(os.path.join(prev, 'end%db.png' % n), b, im)
    # the scroll: end5 (its palette) sliding down over end6
    e5, p5 = pics[5]
    e6 = pics[6][0]
    stack = []
    for r in range(0, 201, 10):
        im = np.concatenate([e5[200 - r:], e6[:200 - r]]) if r else e6.copy()
        stack.append(im)
    s = bf.fit(bf.hist_of(stack), p5)
    snap_to_reps(s, p5)
    open(os.path.join(out, 'ENDS.ISP'), 'wb').write(bytes(s.isp_header()) + c.planar(s.slots(e6))[1])
    blob = b''
    for b in range(4):
        lut = s.luts[b] if b < len(s.luts) else s.luts[-1]
        for im in (e5, e6):
            blob += c.planar(lut[im])[1]
    assert len(blob) == 8 * 32000
    open(os.path.join(out, 'ENDSCR.DAT'), 'wb').write(blob)
    open(os.path.join(out, 'END5.CHK'), 'wb').write(e5.astype(np.uint8).tobytes() + bytes(p5.astype(np.uint8).ravel()))
    open(os.path.join(out, 'END6.CHK'), 'wb').write(e6.astype(np.uint8).tobytes())
    print('ENDS: splits', s.splits, 'err %.0f' % s.err)
    write_inc(inc, scenes, bigfont, list(s.splits) + [200] * (4 - len(s.splits)))
    if prev:
        preview(os.path.join(prev, 'ends.png'), s, stack[10])
    # the credits
    mp = np.frombuffer(open(os.path.join(src, 'main.pal'), 'rb').read()[:768], np.uint8).reshape(256, 3).astype(int)
    cs = [writestr2(a, b_, c_, font) for (a, b_, c_) in CREDITS]
    d = bf.fit(bf.hist_of(cs), mp, own=[(0, 200, [31], 1)])
    snap_to_reps(d, mp)
    save_mode(out, 'CRED', d, np.zeros((200, 320), np.uint8))
    print('CRED: splits', d.splits, 'err %.0f' % d.err)
    if prev:
        preview(os.path.join(prev, 'cred.png'), d, cs[3])
    w, h, img, pal, _ = c.read_cpr(os.path.join(src, 'intro2.cpr'))
    d = bf.fit(bf.hist_of([img]), pal)
    snap_to_reps(d, pal)
    save_mode(out, 'INTRO2E', d, img, pal)
    print('INTRO2E: splits', d.splits, 'err %.0f' % d.err)


if __name__ == '__main__':
    main()
